#!/usr/bin/env python
"""S0 — render both S0 documents from the committed tables (Decisions D13).

  results/s0_baseline/report.md        the measurement report
  docs/naadp_binder_review_2026.md     the verified literature baseline

Neither is hand-written: every number and every citation is read back out of
the TSVs the S0 scripts wrote, so a re-run that changes a table changes the
prose with it and the two cannot drift.

Run after `s0_db_snapshot.py`, `s0_signature_scope.py` and `s0_lit_audit.py`.
"""

from __future__ import annotations

import json
import sys
from datetime import date
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))

from scripts.s0_lib import read_tsv  # noqa: E402

OUT = ROOT / "results" / "s0_baseline"
DOCS = ROOT / "docs"

VERDICT_LABEL = {
    "verified": "verified",
    "qualified": "verified, with a qualification",
    "refined": "verified, wording refined",
    "corrected": "**corrected**",
    "retag": "**re-tagged**",
}


def _cite(refs: list[dict], pmids: str) -> str:
    """Render 'Author YEAR' short cites for a semicolon-joined PMID list."""
    by_pmid = {r["pmid"]: r for r in refs}
    out = []
    for p in [x for x in pmids.split(";") if x]:
        r = by_pmid.get(p)
        if not r:
            out.append(f"PMID:{p}")
            continue
        first = (r.get("authors", "").split(",")[0] or "?").strip()
        surname = first.split()[0] if first else "?"
        out.append(f"{surname} {r.get('year','')} [PMID:{p}]")
    return "; ".join(out)


def render_review(claims: list[dict], refs: list[dict]) -> str:
    """docs/naadp_binder_review_2026.md — the verified baseline."""
    today = date.today().isoformat()
    L: list[str] = []
    A = L.append

    A("# The NAADP-binding proteins — verified literature baseline (2026)")
    A("")
    A(f"*Generated by `scripts/s0_report.py` on {today} from "
      "`results/s0_baseline/lit_claims.tsv` and `references.tsv`. "
      "Do not edit by hand — edit the tables and re-render (Decisions D13).*")
    A("")
    A("This is the S0 deliverable: every `[lit]` claim in "
      "`docs/naadp_binder_background.md`, checked against a primary source. "
      "A claim that failed verification is **struck from the background "
      "document**, not softened. A claim that is true but carried the wrong "
      "evidence tag is re-tagged there.")
    A("")

    counts: dict[str, int] = {}
    for c in claims:
        counts[c["verdict"]] = counts.get(c["verdict"], 0) + 1
    A(f"**{len(claims)} claims audited against {len(refs)} references.** "
      + ", ".join(f"{n} {v}" for v, n in sorted(counts.items())) + ".")
    A("")
    A("---")
    A("")

    sections: dict[str, list[dict]] = {}
    for c in claims:
        sections.setdefault(c["section"], []).append(c)

    for section, items in sections.items():
        A(f"## {section}")
        A("")
        for c in items:
            A(f"### {c['claim_id']} — {VERDICT_LABEL.get(c['verdict'], c['verdict'])}")
            A("")
            A(f"> {c['claim']}")
            A("")
            A(f"**Evidence.** {c['evidence']}")
            A("")
            A(f"**Sources.** {_cite(refs, c['pmids'])}")
            A("")
            A(f"**Action.** {c['action']}")
            A("")
        A("---")
        A("")

    A("## References")
    A("")
    A("Ordered by year. `cited_for` gives the claim IDs each reference "
      "supports; `context` marks a reference cited for background rather "
      "than for a specific audited claim.")
    A("")
    A("| # | Reference | Journal | Year | PMID | DOI | cited_for |")
    A("|---|-----------|---------|------|------|-----|-----------|")
    for i, r in enumerate(refs, start=1):
        authors = r.get("authors", "")
        if len(authors) > 70:
            authors = authors[:70].rsplit(",", 1)[0] + ", et al."
        title = r.get("title", "").replace("|", "/")
        A(f"| {i} | {authors} *{title}* | {r.get('journal','')} | "
          f"{r.get('year','')} | [{r.get('pmid','')}]"
          f"(https://pubmed.ncbi.nlm.nih.gov/{r.get('pmid','')}/) | "
          f"{r.get('doi','')} | {r.get('cited_for_claims','')} |")
    A("")
    return "\n".join(L)


def render_report(symbol: list[dict], coll: list[dict], counts: list[dict],
                  scope: list[dict], recall: list[dict], claims: list[dict],
                  refs: list[dict], meta: dict) -> str:
    """results/s0_baseline/report.md — the S0 measurement report."""
    today = date.today().isoformat()
    L: list[str] = []
    A = L.append

    A("# S0 — literature baseline + scope confirmation")
    A("")
    A(f"*Rendered by `scripts/s0_report.py` on {today} from the tables in "
      "this directory (Decisions D13). Every number below is read back out "
      "of a committed TSV.*")
    A("")

    # --- headline ---
    found = [r for r in symbol if r["result"] == "found"]
    flips = [r for r in symbol if r.get("field_changes_call") == "True"]
    missed = [r for r in recall if r["found_by_planned_pfam"] == "False"]
    A("## Headline")
    A("")
    new_cells = [r for r in found if r.get("field_changes_call") == "True"]
    A(f"- **The setup snapshot reproduces.** {len(found) - len(new_cells)} of "
      f"the {len(symbol)} symbol-table cells resolve to exactly the "
      "accessions and lengths recorded at setup; "
      f"{len(new_cells)} further cell(s) resolve only after the query fix "
      "below. No setup number was contradicted.")
    A(f"- **The census signature for the JPT partition is wrong.** PF17054 "
      "covers less than half its own InterPro family entry, and misses a "
      "reviewed true positive. See *Signature scope*.")
    A("- **A query field, not a genome, produced one of the absences.** "
      f"Switching `organism_id` to `taxonomy_id` changes the call in "
      f"{len(flips)} of {len(symbol)} cells — and the cell it recovers is a "
      "reviewed entry. See *The organism-field artefact*.")
    A(f"- {len(claims)} literature claims audited against {len(refs)} "
      "references; the background document needs one correction, one "
      "refinement, one re-tag.")
    A("- **A blocking app bug was found and fixed**: every `Bio.Entrez` "
      "call in the repo had no timeout. See *Smoke test*.")
    A("")

    # --- symbol table ---
    A("## The symbol table, re-derived")
    A("")
    A(f"Source: `symbol_table.tsv` ({len(symbol)} cells), "
      f"`symbol_table_raw.tsv` (every hit before screening). "
      "Queried live on the date above; screened by length and Pfam, never "
      "by rank (`family.py:SYMBOL_COLLISIONS`).")
    A("")
    A("| Species | JPT2 | LSM12 | JPT1 |")
    A("|---|---|---|---|")
    species_order, seen = [], set()
    for r in symbol:
        if r["species"] not in seen:
            seen.add(r["species"])
            species_order.append(r["species"])
    for sp in species_order:
        cells = []
        for sym in ("JPT2", "LSM12", "JPT1"):
            row = next((r for r in symbol if r["species"] == sp
                        and r["symbol_queried"] == sym), None)
            if not row or row["result"] != "found":
                cells.append("*not found by symbol*")
            else:
                pf = row["pfam"] or "**no Pfam**"
                cells.append(f"{row['accession']} {row['length_aa']} aa "
                             f"({row['status']}) {pf}")
        A(f"| {sp} | " + " | ".join(cells) + " |")
    A("")

    # --- organism field ---
    A("## The organism-field artefact")
    A("")
    A("UniProt's `organism_id` matches **one taxonomy node exactly**; "
      "`taxonomy_id` matches the node **and its descendants**. The setup "
      "snapshot used the first. Both were run here and both are recorded in "
      "`symbol_table.tsv` (`organism_id_result` / `field_changes_call`).")
    A("")
    if flips:
        A("| Cell | taxonomy_id (subtree) | organism_id (exact node) |")
        A("|---|---|---|")
        for f in flips:
            A(f"| {f['species']} / {f['symbol_queried']} | "
              f"{f['result']} — {f['accession']} ({f['length_aa']} aa, "
              f"{f['status']}, {f['pfam']}) | {f['organism_id_result']} |")
        A("")
        A("One cell, and it is a reviewed Swiss-Prot entry carrying both "
          "declared LSM12 signatures. It was invisible because the reviewed "
          "entry sits under the strain node while the project's species "
          "table carries the species node. **This is a false absence "
          "produced by a query field.** The remaining blanks are genuine "
          "naming differences, not this artefact.")
    else:
        A("No cell changed between the two fields in this run.")
    A("")

    # --- signature scope ---
    A("## Signature scope — can the planned census signature see the family?")
    A("")
    A("Source: `signature_scope.tsv`, `signature_recall.tsv`. S2 plans to "
      "enumerate the census from the Pfam IDs in `family.py`. This asks "
      "whether those IDs span their families.")
    A("")
    A("| Partition | Signature | Proteins | InterPro entry | Type | "
      "InterPro proteins | Fraction |")
    A("|---|---|---:|---|---|---:|---:|")
    for r in scope:
        A(f"| {r['partition']} | {r['pfam']} | {r['pfam_proteins'] or '—'} | "
          f"{r['interpro_entry']} {r['interpro_name']} | "
          f"{r['interpro_type']} | {r['interpro_proteins']} | "
          f"{r['pfam_fraction_of_interpro'] or '—'} |")
    A("")
    A("**PF17054 sees 46.2 % of the InterPro Jupiter family entry it "
      "belongs to** (1,360 of 2,944 proteins; the PANTHER member covers the "
      "rest). The LSM12 signatures are effectively complete for their own "
      "entries. So the two partitions need different treatment, and the "
      "asymmetry is not something the roadmap anticipated.")
    A("")
    A(f"Recall against known true positives ({len(recall)} proteins, "
      f"{len(missed)} missed):")
    A("")
    if missed:
        A("| Protein | Accession | Status | Length | Planned Pfam | "
          "Annotated Pfam | InterPro |")
        A("|---|---|---|---:|---|---|---|")
        for m in missed:
            A(f"| {m['label']} | {m['accession']} | {m['status']} | "
              f"{m['length_aa']} | {m['planned_pfam']} | "
              f"{m['pfam_annotated']} | {m['interpro_annotated']} |")
        A("")
        A("Mouse JPT2 is a **reviewed Swiss-Prot** entry and the canonical "
          "mouse ortholog of the human binder. A census built on PF17054 "
          "would not contain it. Both misses carry IPR033335, so the "
          "family-level entry recovers them.")
    A("")

    # --- symbol collision ---
    A("## The HN1L symbol collision, re-measured")
    A("")
    A("Source: `symbol_collision.tsv`.")
    A("")
    A("| Accession | Length | Status | Pfam | Correct? | Longest-first pick? |")
    A("|---|---:|---|---|---|---|")
    for r in coll:
        A(f"| {r['accession']} | {r['length_aa']} | {r['status']} | "
          f"{r['pfam'] or 'none'} | {r['is_expected_correct']} | "
          f"{r['is_longest_first_pick']} |")
    A("")
    A("Reproduced exactly. A longest-first pick selects the wrong protein; "
      "the Pfam screen separates them cleanly, since the decoy carries an "
      "unrelated signature.")
    A("")

    # --- pfam counts ---
    A("## Pfam counts (S2's denominator)")
    A("")
    A("| Pfam | Partition | UniProt proteins |")
    A("|---|---|---:|")
    for r in counts:
        A(f"| {r['pfam']} | {r['partition']} | "
          f"{int(r['uniprot_proteins']):,} |")
    A("")

    # --- literature ---
    A("## Literature audit")
    A("")
    A(f"Source: `lit_claims.tsv`, `references.tsv`. Full text: "
      "`../../docs/naadp_binder_review_2026.md`.")
    A("")
    A("| Claim | Verdict | Action |")
    A("|---|---|---|")
    for c in claims:
        A(f"| {c['claim_id']} — {c['claim'][:64]}… | "
          f"{VERDICT_LABEL.get(c['verdict'], c['verdict'])} | "
          f"{c['action'][:100]}… |")
    A("")

    # --- smoke test ---
    A("## Smoke test")
    A("")
    smoke = OUT / "smoke_test.json"
    if smoke.exists():
        s = json.loads(smoke.read_text())
        A("| Partition | Preset | Variants | Sources returning | Bundle |")
        A("|---|---|---:|---|---|")
        for run in s.get("runs", []):
            A(f"| {run['partition']} | `{run['preset']}` | "
              f"{run['n_variants']} | {run['sources']} | "
              f"{run['bundle'] or '—'} |")
        A("")
        A(s.get("note", ""))
    else:
        A("*(not yet recorded — `smoke_test.json` missing)*")
    A("")
    A("**A blocking bug was found here and fixed.** Every `Bio.Entrez` call "
      "in the repo passed no timeout, and Biopython hands `urlopen` none by "
      "default, so a stalled NCBI read blocks its worker thread forever. "
      "The first smoke-test attempt sat for 15 minutes at 0 % CPU in "
      "`PySSL_select` with the orchestrator's main thread waiting on it. "
      "Fixed in `src/databases/entrez_util.py`, which every Entrez call in "
      "the repo now goes through.")
    A("")

    A("## Provenance")
    A("")
    A(f"- Queries issued for the database snapshot: "
      f"{meta.get('n_queries','?')} (each URL logged in "
      "`snapshot_meta.json`).")
    A(f"- Snapshot date: {meta.get('snapshot_date','?')}; "
      f"Python {meta.get('python','?')}.")
    A("")
    return "\n".join(L)


def main() -> int:
    symbol = read_tsv(OUT / "symbol_table.tsv")
    coll = read_tsv(OUT / "symbol_collision.tsv")
    counts = read_tsv(OUT / "pfam_counts.tsv")
    scope = read_tsv(OUT / "signature_scope.tsv")
    recall = read_tsv(OUT / "signature_recall.tsv")
    claims = read_tsv(OUT / "lit_claims.tsv")
    refs = read_tsv(OUT / "references.tsv")
    meta_path = OUT / "snapshot_meta.json"
    meta = json.loads(meta_path.read_text()) if meta_path.exists() else {}

    missing = [n for n, t in [("symbol_table", symbol), ("pfam_counts", counts),
                              ("signature_scope", scope),
                              ("lit_claims", claims), ("references", refs)]
               if not t]
    if missing:
        print(f"[S0] ERROR: missing/empty tables: {', '.join(missing)}")
        return 1

    review = render_review(claims, refs)
    (DOCS / "naadp_binder_review_2026.md").write_text(review)
    print(f"[S0] wrote docs/naadp_binder_review_2026.md "
          f"({len(review.splitlines())} lines, {len(refs)} references)")

    report = render_report(symbol, coll, counts, scope, recall, claims, refs,
                           meta)
    (OUT / "report.md").write_text(report)
    print(f"[S0] wrote results/s0_baseline/report.md "
          f"({len(report.splitlines())} lines)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
